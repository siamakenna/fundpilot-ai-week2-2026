"""Deterministic human-verification suggestions; never changes analysis findings."""

from .logic import safe_text
from .realworld import markdown as evidence_markdown


def verification_queue(report):
    """One item per unresolved passage, with contradictions before unknowns.

    Scope reminders stay separate from risk counts. Source quotes, offsets and
    reasons are copied, not generated or reinterpreted by a language model.
    """
    passages = {}
    for finding in report["findings"]:
        if finding["key"] == "scope_review" or finding["status"] not in ("NOT MATCH", "UNKNOWN"):
            continue
        item = passages.setdefault(
            finding["id"],
            {k: finding[k] for k in ("id", "start", "end", "quote")}
            | {"criteria": [], "reasons": [], "statuses": [], "kinds": []},
        )
        for field, value in (
            ("criteria", finding["key"]),
            ("reasons", finding["reason"]),
            ("statuses", finding["status"]),
            ("kinds", finding["model_kind"]),
            ("kinds", finding["rule_kind"]),
        ):
            if value not in item[field]:
                item[field].append(value)

    for item in passages.values():
        contradiction = "NOT MATCH" in item["statuses"]
        item["priority"] = 1 if contradiction else 2
        item["label"] = "Resolve a contradiction" if contradiction else "Clarify an uncertainty"
        reasons = " ".join(item["reasons"])
        keys = set(item["criteria"])
        if contradiction:
            item["action"] = (
                "Check the declared facts against your records first. If they are correct, "
                "ask the sponsor before investing time in an application. Do not assume an exception."
            )
            question = (
                "For the condition(s) in this passage, my declared facts produce a contradiction. "
                "Does this prevent me from applying, and is any published exception relevant? "
                "What evidence would you need to confirm?"
            )
        else:
            missing_fact = any(
                phrase in reasons
                for phrase in (
                    "fact not supplied",
                    "fact or a supported stage list is missing",
                    "Enter an amount",
                )
            )
            item["action"] = (
                "Check your records, fill any known corresponding form facts, and analyze again. "
                "If the definition or applicability remains unclear, ask the sponsor."
                if missing_fact
                else "Review this passage with its surrounding conditions and linked policies; ask the sponsor to clarify."
            )
            if "do not agree" in reasons or "Unclassified" in reasons:
                question = (
                    "Which conditions in this passage are mandatory for my situation, and which are "
                    "optional or descriptive? What facts and evidence determine their applicability?"
                )
            elif "Conditional" in reasons or "exclusion" in item["kinds"] or "Negated" in reasons:
                question = (
                    "How do the conditions, exclusions or exceptions in this passage apply to my situation? "
                    "Which pathway and supporting evidence should I use?"
                )
            elif "request_limit" in keys:
                question = (
                    "Does the amount in this passage describe an award benefit or a limit on my request? "
                    "Which currency, eligible expenses and limits apply to my proposed budget?"
                )
            elif "documents" in keys:
                question = (
                    "Which materials in this passage are required for my application, in what format "
                    "and by when? What evidence is acceptable?"
                )
            else:
                question = (
                    "How should I interpret the condition(s) in this passage for my situation, "
                    "and what evidence would establish whether I satisfy them?"
                )
        item["question"] = question
    return sorted(passages.values(), key=lambda item: (item["priority"], item["id"]))


def queue_markdown(report, *, limit=None):
    items = verification_queue(report)
    lines = [
        "## Questions to verify before applying",
        "",
        (
            "Suggestions for human verification, generated by fixed rules—not sponsor answers. "
            "One item per unresolved passage; criterion counts are unchanged. "
            "Share only the relevant facts and public passage with the sponsor, not private documents."
        ),
        "",
    ]
    if not items:
        lines += [
            (
                "No supported contradiction or unresolved criterion was identified. "
                "**This is not eligibility approval.** Review the full announcement, every pasted passage, "
                "exceptions and linked policies before applying."
            ),
            "",
        ]
    for index, item in enumerate(items if limit is None else items[:limit], 1):
        criteria = ", ".join(key.replace("_", " ") for key in item["criteria"])
        lines += [
            f"{index}. **Priority {item['priority']} · {item['label']} · Passage {item['id'] + 1}**",
            f"   - **Criteria:** {safe_text(criteria)}. Findings: {', '.join(item['statuses'])}.",
            f"   - **First action:** {item['action']}",
            f"   - **Suggested sponsor question:** {item['question']}",
            f"   - **Why:** {safe_text(' '.join(item['reasons']))}",
            f"   - **Exact source passage** (characters {item['start']}:{item['end']}): “{safe_text(item['quote'])}”",
            "",
        ]
    if limit is not None and items:
        lines += [
            (
                f"Showing {min(limit, len(items))} of {len(items)} verification items. "
                "Open **Full evidence report and passage review checklist** below, or download the Markdown "
                "report, for the complete numbered list and all underlying findings."
            ),
            "",
        ]
    lines += [
        (
            "**Always verify:** the current application cycle, deadline and timezone, the complete source "
            "and linked policies. Even MATCH findings use self-reported facts and require scope review."
        ),
        "",
    ]
    return "\n".join(lines)


def markdown(report, *, title="Public funding announcement", source_url=""):
    """Add a review queue to the unchanged evidence report used by both UI and CLI."""
    original = evidence_markdown(report, title=title, source_url=source_url)
    return original.replace("## Evidence and checks", queue_markdown(report) + "\n## Evidence and checks", 1)
